#!/bin/bash

# Needed because GameMaker changes the PATH
# variable of the script to be different,
# so we need to get the system PATH variable back.
PATHCMD="$(sh -lc 'echo "export PATH=\"$PATH\""')"
eval "$PATHCMD"

# Go to the project directory
cd `dirname "$0"`

env node ./updateautogeneratedmacros.js

